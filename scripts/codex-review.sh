#!/usr/bin/env sh
# Независимая оценка Codex: тикет против фактического незакоммиченного диффа.
# Запуск: sh scripts/codex-review.sh docs/tickets/T-21-answering.md
#
# Codex 0.149: `exec review` берёт scope из флага ЛИБО инструкции из промта —
# вместе они несовместимы (--uncommitted/--base/--commit ругаются на [PROMPT]).
# Кастомный промт важнее выбора scope, поэтому идём без флага: дефолтный
# scope режима review — незакоммиченные изменения рабочего дерева.
# По той же причине нет и --output-schema: в режиме review он игнорируется,
# вердикт приходит текстом в формате `- [P1] заголовок — file:line`.
set -eu

TICKET="${1:?укажи путь к тикету}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CODEX="${CODEX:-codex}"
OUT="$ROOT/eval/runs/codex-review.md"
ERR="$ROOT/eval/runs/codex-review.err"
mkdir -p "$ROOT/eval/runs"

[ -s "$TICKET" ] || { echo "нет тикета: $TICKET" >&2; exit 2; }

# У `codex exec review` нет --cd, поэтому заходим в корень сами.
cd "$ROOT"

"$CODEX" exec review \
  --output-last-message "$OUT" \
  "Сверь незакоммиченный дифф с тикетом $TICKET: таблица приёмки в нём — это план.

Проект: ErgoVault RAG — ответы по корпусу из 43 заметок с проверкой цитат
кодом (Python, FastAPI, PostgreSQL + pgvector, bge-m3, Claude; фронтенд React).
Правила — в CLAUDE.md, форматы и гарантии — в docs/CONTRACTS.md.

Ищи в таком порядке:
1. Расхождение с тикетом: сделано не то, что решено, или пункт приёмки не закрыт.
2. Нарушение контракта: изменены make_source_id, идентификаторы чанков,
   формат JSONL или схема БД; SQL вне db.py; фильтр public/pilot не в SQL
   одной из ветвей поиска; URL, цитаты или ограничения берутся из ответа
   модели, а не из БД и метаданных; чтение holdout без include_holdout;
   правка corpus/v1/docs или eval/golden; тест переписан под новый результат.
3. Ошибки корректности: необработанные ошибки, потеря данных, сломанные
   границы модулей, прикладной код, импортирующий cli.py или Typer.
4. Код, который выглядит работающим, но не проверен ничем.

Правила:
- Каждое замечание обязано иметь конкретный файл и номер строки. Без них
  не пиши.
- P0/P1 — только то, что реально сломает работу или расходится с тикетом.
  Стилевое и вкусовое — P2/P3.
- Дифф может содержать чужие незакоммиченные правки, которых нет в тикете:
  упомяни их одной строкой в резюме, но не разбирай построчно.
- Не хвали и не пересказывай дифф. Всё чисто — так и скажи одной строкой." \
  > /dev/null 2>"$ERR" || {
    echo "codex review завершился с ошибкой; хвост $ERR:" >&2
    tail -n 5 "$ERR" >&2
    exit 1
  }

[ -s "$OUT" ] || { echo "codex не записал вердикт: $OUT" >&2; exit 1; }
printf 'verdict: %s\n' "$OUT"
